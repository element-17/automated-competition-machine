/**
 * 赛事标题去重键。同一赛事常被多所学校/网站转发，链接不同但标题只差
 * “关于举办……的通知”这类外壳；剥掉外壳后完全一致的视为同一场比赛。
 * 与 discovery 的 competitionKey（第 X 届…）并列：有届次用届次合并，
 * 无届次时用核心名合并；两者都取不到就不合并，宁可保守也不误杀同名校级赛事。
 */

/** 标题里的空白、引号、括号、标点一律去掉。 */
const stripPunctuation = (t: string) =>
  t.replace(
    /[\s"“”'‘’「」『』《》（）()【】\[\]「」、，,。.：:；;！!？?·—–_]+/g,
    "",
  );

export function competitionCoreKey(title: string): string | null {
  // “-共青团XX委员会”这类落款尾段必须在去标点之前剥掉，否则连成一截剥不动。
  let t = title;
  for (;;) {
    const m = /-[^-]{2,25}(?:委员会|办公室|教务处|学生处|团委|工会|中心|网站|平台)$/.exec(
      t,
    );
    if (!m) break;
    t = t.slice(0, m.index);
  }
  t = stripPunctuation(t);
  // 去掉开头的外壳词（可能叠加：“转发关于举办……”）。
  t = t.replace(/^(?:关于|转发|快讯|速递|公告|通知|最新)+/, "");
  t = t.replace(/^(?:举办|开展|组织|启动|做好|举行|征集|收集)+/, "");
  // 去掉结尾的外壳词与附件尾巴，以及“-共青团XX委员会”这类落款。
  t = t.replace(
    /(?:的?)?(?:通知|预通知|公告|函|邀请函|方案|安排)(?:附件\d*)?$/,
    "",
  );
  t = t.replace(/-[^-]{2,25}(?:委员会|办公室|教务处|学生处|团委|中心)$/, "");
  // “2026年”与“2026”视为同一种写法。
  t = t.replace(/年/g, "");
  // 剥完必须仍像赛事标题才构成合并依据；太短容易误杀同名校级赛事。
  if (!/(?:大赛|竞赛|比赛|挑战赛|争霸赛|邀请赛|征集|征文|征稿)/.test(t))
    return null;
  return t.length >= 6 ? t : null;
}
