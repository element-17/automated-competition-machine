export const promptOf = (
  cfg: {
    prompts?: Partial<Record<AgentName, string>>;
    search?: { socialPlatforms?: boolean };
  },
  agent: AgentName,
) => {
  const custom = cfg.prompts?.[agent]?.trim();
  if (custom) return custom;
  const base = defaultPrompts[agent];
  return agent === "research" && cfg.search?.socialPlatforms
    ? `${base}${socialPlatformsResearchAddon}`
    : base;
};
export const isCustomPrompt = (
  cfg: { prompts?: Partial<Record<AgentName, string>> },
  agent: AgentName,
) => !!cfg.prompts?.[agent]?.trim();
